def require_operator_info() -> None:
    required = {
        "TERM_OPERATOR_NAME": OPERATOR_NAME,
        "TERM_OPERATOR_PHONE": OPERATOR_PHONE,
        "TERM_OPERATOR_EMAIL": OPERATOR_EMAIL,
    }

    missing = [
        key
        for key, value in required.items()
        if not value
    ]

    if missing:
        joined = ", ".join(missing)

        raise RuntimeError(
            "약관을 운영 DB에 저장하려면 다음 값을 "
            f".env에 먼저 설정해야 합니다: {joined}"
        )


