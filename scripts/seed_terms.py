# 기존 약관은 삭제하지 않고 기록으로 보존한 채
# API에서 노출되지 않도록 비활성화합니다.
#
# LOCATION_BASED_SERVICE는 현재 서비스가 기기 GPS나 현재 위치정보를
# 수집·이용하지 않으므로 새 버전을 생성하지 않습니다.
INACTIVE_TERM_IDS = (
    "TERMS_OF_SERVICE_1.0",
    "TERMS_OF_SERVICE_1.1",
    "PRIVACY_POLICY_1.0",
    "PRIVACY_POLICY_1.1",
    "LOCATION_BASED_SERVICE_1.0",
    "LOCATION_BASED_SERVICE_1.1",
    "MARKETING_1.0",
    "MARKETING_1.1",
)


def deactivate_old_terms() -> None:
    client = get_firestore_client()
    collection = client.collection("terms")

    for term_id in INACTIVE_TERM_IDS:
        reference = collection.document(term_id)
        snapshot = reference.get()

        if not snapshot.exists:
            print(
                f"[기존 약관 없음] terms/{term_id}"
            )
            continue

        reference.update(
            {
                "active": False,
            }
        )

        print(
            f"[비활성화] terms/{term_id}"
        )


def seed_terms() -> None:
    require_operator_info()

    repository = TermRepository()

    # 새 약관을 먼저 저장한 뒤 기존 약관을 비활성화합니다.
    for term_id, term in TERMS.items():
        repository.set_term(
            term_id,
            term,
        )

        print(
            f"[저장 완료] terms/{term_id}: "
            f"{term.title}"
        )

    deactivate_old_terms()

    print(
        f"\n총 {len(TERMS)}개 활성 약관 1.2 저장 완료"
    )


if __name__ == "__main__":
    seed_terms()
